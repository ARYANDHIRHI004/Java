public class Main {
    public static void main(String[] args) {
        //Arithmetic operators
        int num1 = 876;
        int num2 = 6354;

        System.out.println(num1+num2);
        System.out.println(num1-num2);
        System.out.println(num1*num2);
        System.out.println((float)num1/num2);
        System.out.println(num1 % num2);

        //Increment and Decrement Operator
        int a = 5;
        a++;
        System.out.println(a);
        a--;
        System.out.println(a);

    }
}