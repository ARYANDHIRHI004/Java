public class typeCasting {
    public static void main(String[] args) {
        int a = 10;
        
        float b = a;
        System.out.println(b);

        float c = 12.5f;
        int d = (int)c;
        System.out.println(d);

        int n1 = 10;
        int n2 = 3;

        float res = n1/n2;
        System.out.println(res);
        
        
    }
}
